// Package web renders the nginx configuration that fronts the node: TLS termination, the decoy tree,
// the proxy path to Xray on loopback, and the endpoints the decoy page needs.
//
// The decoy page and the nginx fragment that answers its sign-in form are generated from the same
// data (one decoy.Site), so the form's action, the response body and the cookie cannot drift apart.
// nginx serves the site; the agent never listens on :80 or :443.
package web

import (
	"bytes"
	"errors"
	"fmt"
	"strings"
	"text/template"

	"github.com/shogun-kub/termit/internal/uv/decoy"
)

// decoyTemplate is the server-block fragment for the masking site.
//
// `return` answers before any application could, which is the point: there is no application. The
// status, the JSON body and the cookie are the site's own, and $request_id makes each answer look
// like a real request that was logged somewhere.
var decoyTemplate = template.Must(template.New("decoy").Parse(`# Decoy endpoints, generated by termit-uv from the site data.
# Do not edit: ` + "`uv renew-site`" + ` rewrites this file.

error_page 404 /404.html;

location = {{.Auth.Path}} {
    if ($request_method != {{.Auth.Method}}) {
        return 405;
    }
    default_type {{.Auth.ContentType}};
    add_header Set-Cookie "{{.Auth.Cookie}}" always;
    add_header Cache-Control "no-store" always;
    add_header X-Request-Id $request_id always;
    return {{.Auth.Status}} '{{.Auth.Body}}';
}
`))

// DecoySnippet renders the server-block fragment for one generated site.
func DecoySnippet(site *decoy.Site) ([]byte, error) {
	if site == nil {
		return nil, errors.New("web: a generated site is required")
	}
	if err := validateRoute(site.Auth); err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := decoyTemplate.Execute(&buf, site); err != nil {
		return nil, fmt.Errorf("web: render decoy snippet: %w", err)
	}
	return buf.Bytes(), nil
}

// validateRoute refuses values that would need escaping in an nginx configuration. The route comes
// from our own generator, so this is a guard against a future template change, not against input.
func validateRoute(route decoy.AuthRoute) error {
	switch {
	case !strings.HasPrefix(route.Path, "/"):
		return fmt.Errorf("web: auth path %q must start with /", route.Path)
	case strings.ContainsAny(route.Path, " \t\r\n;{}"):
		return fmt.Errorf("web: auth path %q contains a character nginx would misread", route.Path)
	case route.Method != "POST" && route.Method != "GET":
		return fmt.Errorf("web: auth method %q is not supported", route.Method)
	case strings.ContainsAny(route.Body, "'\r\n"):
		return errors.New("web: auth body contains a quote or newline that nginx would misread")
	case strings.ContainsAny(route.Cookie, "\"\r\n"):
		return errors.New("web: auth cookie contains a quote or newline that nginx would misread")
	}
	return nil
}
