// Package service renders the systemd units Termit installs.
//
// The units are generated, not shipped as files: every path in them comes from the configuration, and
// a unit that hardcodes /usr/lib/termit could not be installed anywhere else. They are deliberately
// strict — the proxy core needs no capability, no writable path and no device — because a proxy that
// runs as root with a wide surface is a worse trade than a proxy that cannot write anything.
package service

import (
	"fmt"
	"path/filepath"
	"strings"
)

// XrayUnitName is the unit that runs the proxy core.
const XrayUnitName = "termit-xray.service"

// NginxDropInName is the drop-in directory entry for the distribution's nginx unit.
const NginxDropInName = "termit.conf"

const unitHeader = `# Generated by termit-uv. Do not edit: ` + "`uv init`" + ` rewrites this file.
`

// Xray renders the proxy core's unit. binary and config must be absolute paths.
func Xray(binary, config string) ([]byte, error) {
	if !filepath.IsAbs(binary) && !strings.HasPrefix(binary, "/") ||
		!filepath.IsAbs(config) && !strings.HasPrefix(config, "/") {
		return nil, fmt.Errorf("service: binary %q and config %q must be absolute paths", binary, config)
	}
	var b strings.Builder
	b.WriteString(unitHeader)
	fmt.Fprintf(&b, `
[Unit]
Description=Termit proxy core
Documentation=https://github.com/shogun-kub/termit
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
User=termit
Group=termit
ExecStart=%s run -config %s
Restart=on-failure
RestartSec=3s
LimitNOFILE=65535
UMask=0077

# The core listens on loopback and reads one file. Everything else is taken away.
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=multi-user.target
`, binary, config)
	return []byte(b.String()), nil
}

// NginxDropIn renders the hardening drop-in for the distribution's nginx unit. It stays small on
// purpose: nginx still binds :80 and :443 and drops to www-data, so only the parts that are safe for
// any nginx are changed here.
func NginxDropIn() ([]byte, error) {
	var b strings.Builder
	b.WriteString(unitHeader)
	b.WriteString(`
[Service]
# One descriptor per proxy connection; the stock limit is far too low for a proxy.
LimitNOFILE=65535
# nginx does not need the host's /tmp, and it never needs a home directory.
PrivateTmp=yes
ProtectHome=yes
`)
	return []byte(b.String()), nil
}
