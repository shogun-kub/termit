// Package service renders the systemd units Termit installs.
//
// The units are generated, not shipped as files: every path in them comes from the configuration, and
// a unit that hardcodes /usr/lib/termit could not be installed anywhere else. They are deliberately
// strict — the proxy core needs no capability, no writable path and no device — because a proxy that
// runs as root with a wide surface is a worse trade than a proxy that cannot write anything.
package service

import (
	"fmt"
	"path"
	"path/filepath"
	"strings"
)

// XrayUnitName is the unit that runs the proxy core.
const XrayUnitName = "termit-xray.service"

// AgentUnitName is the long-running agent: the daily cycle, the local self-check and the peer sync.
const AgentUnitName = "termit-uv-agent.service"

// RenewUnitName and RenewTimerName run `renew-cert` on a schedule. The timer, not the agent, owns the
// clock: a daily oneshot is easier to inspect than a sleep loop, and it survives a reboot.
const (
	RenewUnitName  = "termit-uv-renew.service"
	RenewTimerName = "termit-uv-renew.timer"
)

// NginxDropInName is the drop-in directory entry for the distribution's nginx unit.
const NginxDropInName = "termit.conf"

const unitHeader = `# Generated by termit-uv. Do not edit: ` + "`uv init`" + ` rewrites this file.
`

// Xray renders the proxy core's unit. binary and config must be absolute paths.
func Xray(binary, config string) ([]byte, error) {
	if !filepath.IsAbs(binary) && !strings.HasPrefix(binary, "/") ||
		!filepath.IsAbs(config) && !strings.HasPrefix(config, "/") {
		return nil, fmt.Errorf("service: binary %q and config %q must be absolute paths", binary, config)
	}
	var b strings.Builder
	b.WriteString(unitHeader)
	fmt.Fprintf(&b, `
[Unit]
Description=Termit proxy core
Documentation=https://github.com/shogun-kub/termit
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
User=termit
Group=termit
ExecStart=%s run -config %s
Restart=on-failure
RestartSec=3s
LimitNOFILE=65535
UMask=0077

# The core listens on loopback and reads one file. Everything else is taken away.
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
CapabilityBoundingSet=
AmbientCapabilities=

[Install]
WantedBy=multi-user.target
`, binary, config)
	return []byte(b.String()), nil
}

// Agent renders the long-running node agent: the daily cycle, the self-check and the peer sync. It
// runs as root because it rewrites the core's configuration and asks systemd to restart the core,
// and it is confined to exactly the paths it writes plus the files it has to read. writable and
// readable come from the configuration, not from this file.
func Agent(binary, config string, writable, readable []string) ([]byte, error) {
	if !filepath.IsAbs(binary) && !strings.HasPrefix(binary, "/") {
		return nil, fmt.Errorf("service: binary %q must be an absolute path", binary)
	}
	if !filepath.IsAbs(config) && !strings.HasPrefix(config, "/") {
		return nil, fmt.Errorf("service: config %q must be an absolute path", config)
	}
	paths, err := absolutePaths(writable)
	if err != nil {
		return nil, err
	}
	readOnly, err := absolutePaths(readable)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString(unitHeader)
	fmt.Fprintf(&b, `
[Unit]
Description=Termit node agent
Documentation=https://github.com/shogun-kub/termit
After=network-online.target termit-xray.service
Wants=network-online.target
StartLimitIntervalSec=300
StartLimitBurst=5

[Service]
Type=simple
ExecStart=%s agent -v --config %s
Restart=on-failure
RestartSec=30s
Nice=10

# The agent needs root for two reasons: the core config is 0640 root:termit, and a validated restart
# goes through systemd. Everything else is taken away, and its writes are confined to the paths below.
NoNewPrivileges=yes
ProtectSystem=strict
ReadWritePaths=%s
`, binary, config, strings.Join(paths, " "))
	if len(readOnly) > 0 {
		fmt.Fprintf(&b, "ReadOnlyPaths=%s\n", strings.Join(readOnly, " "))
	}
	// ProtectHome= hides /home, /root and /run/user, including paths a unit explicitly asked to read
	// with ReadOnlyPaths= (the mount ordering is not something a unit can rely on). The MN CA file is
	// operator-supplied and may live there, so the hardening is dropped when it would break a read
	// the unit was configured for.
	if hidesAReadablePath(readOnly) {
		b.WriteString("# ProtectHome is off: a readable path (the MN CA file) lives under a home directory.\n")
	} else {
		b.WriteString("ProtectHome=yes\n")
	}
	b.WriteString(`PrivateTmp=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
SystemCallArchitectures=native

[Install]
WantedBy=multi-user.target
`)
	return []byte(b.String()), nil
}

// hidesAReadablePath reports whether any path lies under a directory ProtectHome= makes inaccessible.
func hidesAReadablePath(paths []string) bool {
	for _, p := range paths {
		switch {
		case p == "/root" || strings.HasPrefix(p, "/root/"),
			p == "/home" || strings.HasPrefix(p, "/home/"),
			p == "/run/user" || strings.HasPrefix(p, "/run/user/"):
			return true
		}
	}
	return false
}

// absolutePaths validates and de-duplicates a list for ReadWritePaths. systemd refuses a relative
// path there, and a typo must fail the unit render instead of producing a unit that cannot start.
func absolutePaths(paths []string) ([]string, error) {
	seen := make(map[string]bool, len(paths))
	out := make([]string, 0, len(paths))
	for _, p := range paths {
		if p == "" {
			continue
		}
		if !filepath.IsAbs(p) && !strings.HasPrefix(p, "/") {
			return nil, fmt.Errorf("service: writable path %q must be absolute", p)
		}
		clean := path.Clean(p)
		if seen[clean] {
			continue
		}
		seen[clean] = true
		out = append(out, clean)
	}
	return out, nil
}

// Renew renders the oneshot unit that renews the certificate once. The binary is the one that wrote
// this unit, so a node upgrades its renewal path together with itself.
func Renew(binary, config string) ([]byte, error) {
	if !filepath.IsAbs(binary) && !strings.HasPrefix(binary, "/") {
		return nil, fmt.Errorf("service: binary %q must be an absolute path", binary)
	}
	var b strings.Builder
	b.WriteString(unitHeader)
	fmt.Fprintf(&b, `
[Unit]
Description=Termit certificate renewal
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=%s renew-cert --config %s
Nice=10
NoNewPrivileges=yes
ProtectHome=yes
PrivateTmp=yes
`, binary, config)
	return []byte(b.String()), nil
}

// RenewTimer renders the daily timer. The jitter keeps a fleet from waking at the same second, and
// Persistent makes a missed run happen after a reboot instead of being skipped.
func RenewTimer() ([]byte, error) {
	var b strings.Builder
	b.WriteString(unitHeader)
	b.WriteString(`
[Unit]
Description=Renew the Termit certificate daily

[Timer]
OnCalendar=daily
RandomizedDelaySec=1h
Persistent=true
AccuracySec=1min

[Install]
WantedBy=timers.target
`)
	return []byte(b.String()), nil
}

// NginxDropIn renders the hardening drop-in for the distribution's nginx unit. It stays small on
// purpose: nginx still binds :80 and :443 and drops to www-data, so only the parts that are safe for
// any nginx are changed here.
func NginxDropIn() ([]byte, error) {
	var b strings.Builder
	b.WriteString(unitHeader)
	b.WriteString(`
[Service]
# One descriptor per proxy connection; the stock limit is far too low for a proxy.
LimitNOFILE=65535
# nginx does not need the host's /tmp, and it never needs a home directory.
PrivateTmp=yes
ProtectHome=yes
`)
	return []byte(b.String()), nil
}
